/* 用于练习分析效率的递归函数。
 * 跟踪递归的工作过程，并据此形成关于以下内容的假设：
 * 运行时。
 */
int recursivePuzzle(int n) {
    if (n == 0) {
        return 1;
    }
    return 1 + recursivePuzzle(n - 1);
}

/* 用于练习分析效率的递归函数。
 * 跟踪递归的工作过程，并据此形成关于以下内容的假设：
 * 运行时。
 */
int recursiveEnigma(int n) {
    if (n == 0) {
        return 1;
    }
    return 1 + recursiveEnigma(n / 2);
}

