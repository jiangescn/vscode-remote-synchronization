/* 打印一个宽为 n 个字符、高为 n 个字符的字母 H
 * 高。例如，调用 printH(5) 会打印
 *
 *       *   *
 *       *   *
 *       *****
 *       *   *
 *       *   *
 *
 * 调用 printH(7) 会打印
 *
 *       *     *
 *       *     *
 *       *     *
 *       *******
 *       *     *
 *       *     *
 *       *     *
 */
void printH(int n) {
    for (int row = 0; row < n; row++) {
        for (int col = 0; col < n; col++) {
            /* 如果字符位于最开始或最后，则它是星号
             * 列，或者它位于中间行。
             */
            if (row == n / 2 || col == 0 || col == n - 1) {
                cout << '*';
            }
            /* 否则，它为空白。 */
            else {
                cout << ' ';
            }
        }
        cout << endl;
    }
}

/* 打印一个宽和高均为 n 个字符的字母 C。
 *
 * 例如，printC(4) 打印
 *
 *       ****
 *       *
 *       *
 *       ****
 *
 * 调用 printC(10) 会打印
 *
 *       **********
 *       *
 *       *
 *       *
 *       *
 *       *
 *       *
 *       *
 *       *
 *       **********
 */
void printC(int n) {
    for (int row = 0; row < n; row++) {
        /* 第一行/最后一行打印一整行星号。 */
        if (row == 0 || row == n - 1) {
            for (int col = 0; col < n; col++) {
                cout << '*';
            }
            cout << endl;
        }
        /* 其他每一行只打印一个星号。 */
        else {
            cout << '*' << endl;
        }
    }
}

/* 打印一个宽为 n 个字符、高为 n 个字符的字母 I
 * 高。例如，调用 printI(5) 会打印
 *
 *       *****
 *         *
 *         *
 *         *
 *       *****
 *
 * 调用 printI(7) 会打印
 *
 *       *******
 *          *
 *          *
 *          *
 *          *
 *          *
 *       *******
 */
void printI(int n) {
    for (int row = 0; row < n; row++) {
        /* 顶部和底部两行全部是星号。 */
        if (row == 0 || row == n - 1) {
            for (int col = 0; col < n; col++) {
                cout << '*';
            }
        }
        /* 其他每一行都需要在中点处有一个星号。 */
        else {
            for (int col = 0; col < (n / 2); col++) {
                cout << ' ';
            }
            cout << '*';
        }
        cout << endl;
    }
}

/* 打印一个宽为 n 个字符、高为 n 个字符的字母 P
 * 高。例如，调用 printP(5) 会打印
 *
 *       *****
 *       *   *
 *       *****
 *       *
 *       *
 *
 * 调用 printP(7) 会打印
 *
 *       *******
 *       *     *
 *       *     *
 *       *******
 *       *
 *       *
 *       *
 */
void printP(int n) {
    for (int row = 0; row < n; row++) {
        /* 顶部和中间两行全部是星号。 */
        if (row == 0 || row == n / 2) {
            for (int col = 0; col < n; col++) {
                cout << '*';
            }
        }
        /* 上半部分其他每一行在开头和末尾各有一个星号。 */
        else if (row < n / 2) {
            for (int col = 0; col < n; col++) {
                if (col == 0 || col == n - 1) {
                    cout << '*';
                } else {
                    cout << ' ';
                }
            }
        }
        /* 其余所有行只在开头有一个星号。 */
        else {
            cout << '*';
        }
        cout << endl;
    }
}

/* 使用给定大小的字母打印单词 "CHIP"。 */
void printChip(int n) {
    printC(n);
    cout << endl;
    printH(n);
    cout << endl;
    printI(n);
    cout << endl;
    printP(n);
}

